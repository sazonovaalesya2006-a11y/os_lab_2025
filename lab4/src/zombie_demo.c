#include <stdio.h>
#include <stdlib.h>
#include <unistd.h>
#include <sys/wait.h>

int main() {
    pid_t pid = fork();

    if (pid < 0) {
        perror("Fork failed");
        exit(1);
    } else if (pid == 0) {
        // Дочерний процесс
        printf("Дочерний процесс (PID: %d) запущен и сейчас завершится.\n", getpid());
        exit(0); // Ребенок сразу же завершает работу
    } else {
        // Родительский процесс
        printf("Родительский процесс (PID: %d) создал ребенка с PID: %d.\n", getpid(), pid);
        printf("Родитель будет спать 15 секунд и НЕ будет вызывать wait().\n");
        printf("Пока родитель спит, ребенок становится ЗОМБИ.\n");
        
        // Спим, чтобы вы успели посмотреть на зомби в другой вкладке терминала
        sleep(15); 

        // "Собираем" (reap) дочерний процесс, чтобы удалить зомби
        wait(NULL);
        printf("Родитель вызвал wait(). Зомби-процесс удален из таблицы процессов.\n");
    }
    return 0;
}
