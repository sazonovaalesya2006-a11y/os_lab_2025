#!/bin/bash

# Проверяем, есть ли аргументы
if [ $# -eq 0 ]; then
    echo "Ошибка: введите числа в качестве аргументов"
    exit 1
fi

# Считаем количество аргументов
count=$#

# Суммируем все аргументы
sum=0
for arg in "$@"; do
    sum=$((sum + arg))
done

# Выводим количество и среднее арифметическое
echo "Количество аргументов: $count"
echo "Среднее арифметическое: $((sum / count))"
